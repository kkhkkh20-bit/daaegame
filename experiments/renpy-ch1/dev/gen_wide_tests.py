"""Generate the wide-map Ren'Py testcases (0.18.57) into game/qa_tests/tests.rpy.

    python3 dev/gen_wide_tests.py          # rewrite the generated block

For each wide location, period and camera (0/440/880) the test:
  * records a hit map (Ren'Py's own focus lookup over every object rect and
    every staged resident) and a screenshot,
  * clicks each visible investigation object at a point the hit map found to
    belong to that object (so a toolbar or a face over the object is reported,
    not silently hit) and logs what the click actually chose.
Period-limited layouts (post: morning only) also check the old 1280 scene in the
other periods. The block between the markers is replaced on every run.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TESTS = ROOT / "game/qa_tests/tests.rpy"
LAYOUT = json.loads((ROOT / "game/assets/room13-world-layout.json").read_text())
BEGIN = "# ---- generated by dev/gen_wide_tests.py (begin) ----"
END = "# ---- generated by dev/gen_wide_tests.py (end) ----"
CAMERAS = (0, 440, 880)
# Day per period with the most residents at that place (days 1-13 schedule);
# evening uses day 7 (day 2 evening holds story events before the hub).
DAYS = {
    "kitchen": {0: 2, 1: 2, 2: 7},
    "dining": {0: 2, 1: 2, 2: 7},
    "passage": {0: 2, 1: 2, 2: 7},
    "post": {0: 3, 1: 3, 2: 7},
    # 0.18.57 inn lobby repair art (layout unchanged); evening with Bami protected = 7 people.
    "inn": {0: 3, 1: 3, 2: 7},
}
EXTRA_FLAGS = {("inn", 2): '("bami_protected",)'}
FLAGS = '("lodging","entry_corrected")'
PERIOD_NAME = ("morning", "afternoon", "evening")
# Scenes drawn per case state (hall, 13호): (state, day per period, setup, flags).
# Episode flags skip the day-2/3 evening scenes that would hold the hub.
QUIET = '("ep1_patrol_seen","ep1_eaves_seen")'
STATES = {
    "hall": [("before", {0: 3, 1: 3, 2: 3}, 'room13.update(case_state="pending",victim_state="alive")', QUIET),
             ("after", {0: 6, 1: 6, 2: 6}, 'room13.update(case_state="occurred",victim_state="dead",daram_state="held")', QUIET)],
    "room13": [("before", {0: 3, 1: 3, 2: 3}, 'room13.update(case_state="pending",victim_state="alive",daram_state="with_dad")', QUIET),
               ("after", {0: 6, 1: 6, 2: 6}, 'room13.update(case_state="occurred",victim_state="dead",daram_state="held")', QUIET)],
}


def visible(rect, camera):
    # At least 30px of the object inside the 1280 view.
    x, y, w, h = rect
    return min(x + w, camera + 1280) - max(x, camera) >= 30


def goto(loc, day, period, camera, setup=None, flags=None):
    flags = flags or EXTRA_FLAGS.get((loc, period))
    call = f'    run Call("r13_qa_goto",{day},{period},"{loc}",{flags})' if flags else f'    run Call("r13_qa_goto",{day},{period},"{loc}")'
    return ([f"    $ {setup}"] if setup else []) + [
        f'    $ r13_world_cameras={{"{loc}":{camera}}}',
        call,
        '    click pos (640,600) until screen "r13_hub" timeout 40',
        '    pause 1.0',
    ]


def location_case(loc):
    spec = LAYOUT[loc]
    periods = spec.get("periods", ["morning", "afternoon", "evening"])
    out = [f"testcase wide_{loc}:",
           f"    # 0.18.57 wide map {loc}: hit map, screenshot and real clicks per state, period and camera.",
           "    pause 2.0", '    click "처음부터"', "    pause 3.0",
           f'    run Call("r13_qa_roam",dict(day=2,period=0,location="{loc}",life_poc=True,secret_route_unlocked=True),{FLAGS})',
           '    click pos (640,600) until screen "r13_hub" timeout 40', "    pause 0.6"]
    objects = dict(spec["objects"], **spec.get("late_objects", {}))
    for state, days, setup, flags in STATES.get(loc, [(None, DAYS.get(loc), None, None)]):
        tag = loc + ("_" + state if state else "")
        for period in range(3):
            day = days[period]
            name = PERIOD_NAME[period]
            if name not in periods:
                # Old 1280 scene stays: one view, its own rects, no wide clicks.
                out += goto(loc, day, period, 0, setup, flags)
                out += [f'    $ r13_qa_hitmap("{tag}_p{period}_old")',
                        f'    screenshot "{tag}_{name}_old.png"',
                        f"    assert eval (r13_world_width()==1280)"]
                continue
            width = int(spec.get("width", 1280))
            for camera in (0, (width - 1280) // 2, width - 1280):
                out += goto(loc, day, period, camera, setup, flags)
                out += [f'    $ r13_qa_hitmap("{tag}_p{period}_c{camera}")',
                        f'    screenshot "{tag}_{name}_c{camera}.png"',
                        f"    assert eval (r13_world_width()=={width} and r13_world_offset()=={camera})"]
                if state:
                    out.append(f'    assert eval (r13_world_file("{loc}",r13_daylight()).endswith("-{state}-{name}.webp"))')
                for key, rect in objects.items():
                    if not visible(rect, camera):
                        continue
                    out += goto(loc, day, period, camera, setup, flags)
                    out += [f'    $ r13_qa_hitmap("{tag}_p{period}_c{camera}_{key}_pre")',
                            f'    if eval ("{key}" in R13_QA_PICK):',
                            "        $ r13_qa_wide_reset_choice()",
                            f'        click pos r13_qa_pick("{key}")',
                            "        pause 0.8",
                            f'        $ r13_qa_wide_log("{tag}_p{period}_c{camera}_{key}","{key}")']
    out.append("")
    return out


def saveload_case():
    out = ["testcase wide_saveload:",
           "    # 0.18.57: each period's picture and rects survive save/load and period changes;",
           "    # post keeps the old scene outside the morning.",
           "    pause 2.0", '    click "처음부터"', "    pause 3.0",
           f'    run Call("r13_qa_roam",dict(day=2,period=0,location="dining",life_poc=True,secret_route_unlocked=True),{FLAGS})',
           '    click pos (640,600) until screen "r13_hub" timeout 40', "    pause 0.6"]
    table = LAYOUT["dining"]["objects"]["table"]
    for period, day in ((0, 2), (1, 2)):
        name = PERIOD_NAME[period]
        out += goto("dining", day, period, 440)
        out += [f'    $ r13_qa_wide_log("dining_{name}")',
                f'    assert eval (r13_world_width()==2160 and ROOM13["objects"]["dining"]["table"]["rect"]=={table} and r13_world_background is not None and r13_layout()["files"][r13_daylight()].endswith("dining-{name}.webp"))',
                f'    $ renpy.save("qa-wide-{name}","qa")', "    pause 0.5"]
    # Period change inside one location: morning -> afternoon -> evening.
    out += goto("kitchen", 2, 0, 440)
    out += ['    $ r13_qa_wide_log("kitchen_morning")']
    out += goto("kitchen", 2, 1, 440)
    out += ['    $ r13_qa_wide_log("kitchen_afternoon")',
            '    assert eval (r13_layout()["files"][r13_daylight()].endswith("kitchen-afternoon.webp"))']
    for name in ("afternoon", "morning"):
        out += [f'    run Function(renpy.load,"qa-wide-{name}")', "    pause 2.0",
                f'    $ r13_qa_wide_log("dining_after_load_{name}")',
                f'    assert eval (r13_daylight()=="{name}" and r13_world_width()==2160 and ROOM13["objects"]["dining"]["table"]["rect"]=={table})',
                f'    screenshot "dining_after_load_{name}.png"']
    # Dining evening (third floor spot), then back to the afternoon picture.
    out += goto("dining", 7, 2, 0)
    out += ['    $ r13_qa_wide_log("dining_evening")',
            f'    assert eval (r13_world_width()==2160 and r13_world_file("dining","evening").endswith("dining-evening.webp") and ROOM13["objects"]["dining"]["table"]["rect"]=={table})']
    out += goto("dining", 7, 1, 440)
    out += [f'    assert eval (r13_world_width()==2160 and r13_world_file("dining",r13_daylight()).endswith("dining-afternoon.webp"))']
    # 13호/hall: the picture follows the case state, also across save/load.
    bed = LAYOUT["room13"]["objects"]["bed"]
    out += goto("room13", 3, 1, 440, 'room13.update(case_state="pending",victim_state="alive",daram_state="with_dad")', QUIET)
    out += ['    $ r13_qa_wide_log("room13_before_save")',
            '    assert eval (r13_world_file("room13","afternoon").endswith("room13-before-afternoon.webp"))',
            '    $ renpy.save("qa-wide-room13","qa")', "    pause 0.5"]
    out += goto("room13", 6, 1, 440, 'room13.update(case_state="occurred",victim_state="dead",daram_state="held")', QUIET)
    out += ['    $ r13_qa_wide_log("room13_after")',
            '    assert eval (r13_world_file("room13","afternoon").endswith("room13-after-afternoon.webp") and r13_world_file("hall","evening").endswith("hall-after-evening.webp"))',
            '    screenshot "room13_after_afternoon.png"',
            '    run Function(renpy.load,"qa-wide-room13")', "    pause 2.0",
            '    $ r13_qa_wide_log("room13_after_load")',
            f'    assert eval (room13["case_state"]=="pending" and r13_world_file("room13",r13_daylight()).endswith("room13-before-afternoon.webp") and ROOM13["objects"]["room13"]["bed"]["rect"]=={bed})',
            '    screenshot "room13_before_after_load.png"',
            # guestroom keeps the old picture and rects.
            '    assert eval (ROOM13["objects"]["guestroom"]["bed"]["rect"]==[605,311,537,151] and "guestroom" not in R13_WORLD_LAYOUTS)']
    # Post: wide in the morning, the old scene in the afternoon.
    out += goto("post", 3, 0, 440)
    out += ['    $ r13_qa_wide_log("post_morning")',
            '    assert eval (r13_world_width()==2160)']
    out += goto("post", 3, 1, 0)
    out += ['    $ r13_qa_wide_log("post_afternoon_old")',
            '    assert eval (r13_world_width()==1280)']
    out += goto("kitchen", 3, 0, 440)
    out += ['    $ room13["case_state"]="occurred"']
    out += goto("kitchen", 3, 0, 440)
    rear = LAYOUT["kitchen"]["objects"]["rear"]
    out += ['    $ r13_qa_wide_log("kitchen_after_case")',
            f'    assert eval (ROOM13["objects"]["kitchen"]["rear_after"]["rect"]==ROOM13["objects"]["kitchen"]["rear"]["rect"]=={rear})',
            '    screenshot "kitchen_after_case_morning.png"', ""]
    return out


def capacity_case():
    return ["testcase wide_capacity:",
            "    # 0.18.57: residents never outnumber a wide layout's reviewed slots (days 1-14,",
            "    # every period, case/victim/granny states and the flags that move people).",
            "    pause 2.0", '    click "처음부터"', "    pause 3.0",
            f'    run Call("r13_qa_roam",dict(day=2,period=0,location="kitchen",life_poc=True,secret_route_unlocked=True),{FLAGS})',
            '    click pos (640,600) until screen "r13_hub" timeout 40', "    pause 0.6",
            "    assert eval r13_qa_wide_capacity()", ""]


def main():
    text = TESTS.read_text()
    block = [BEGIN]
    for loc in [l for l in ("kitchen", "dining", "passage", "post", "inn", "hall", "room13") if l in LAYOUT]:
        block += location_case(loc)
    block += saveload_case() + capacity_case() + [END]
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1]
    else:
        # First run: replace the hand-written 0.18.57 cases at the end of the file.
        head = text.split("testcase wide_kitchen:", 1)[0]
        tail = "\n"
    TESTS.write_text(head + "\n".join(block) + tail)
    print("wrote", sum(1 for l in block if l.startswith("testcase")), "testcases")


if __name__ == "__main__":
    main()
